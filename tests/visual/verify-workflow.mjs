import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: process.env.FRUITY_BROWSER_CHANNEL || undefined });
const page = await browser.newPage({ viewport: { width: 800, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => {
  window.fixtureClipboard = '';
  Object.defineProperty(navigator, 'clipboard', { value: { writeText: async value => { window.fixtureClipboard = value; } } });
});
try {
  await page.goto(process.env.FRUITY_WORKFLOW_URL ?? 'http://127.0.0.1:1421/tests/visual/workflow.html');
  await page.getByRole('button', { name: 'Choose example file…' }).click();
  await expect(page.locator('#selected-file')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Change file' })).toBeFocused();
  await page.getByText('File details', { exact: true }).click();
  await expect(page.locator('.fr-file__path')).toBeVisible();
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Choose example file…' })).toBeFocused();
  await page.locator('#drop-state').selectOption('locked');
  await expect(page.getByRole('button', { name: 'Choose example file…' })).toBeDisabled();
  await page.locator('#drop-state').selectOption('rejected');
  await expect(page.locator('#drop-title')).toHaveText('Choose one file at a time');
  await page.locator('#operation-action').click();
  await expect(page.locator('#operation')).toHaveAttribute('data-state', 'starting');
  await expect(page.locator('#operation-meter')).not.toHaveAttribute('aria-valuenow');
  await page.locator('#operation-state').selectOption('hashing');
  await expect(page.locator('#operation-meter')).toHaveAttribute('aria-valuenow', '42');
  await page.locator('#operation-action').click();
  await expect(page.locator('#operation-action')).toBeDisabled();
  await expect(page.locator('#operation-state')).toBeFocused();
  await page.locator('#operation-state').selectOption('canceled');
  await expect(page.locator('#operation-description')).toHaveText('No results were kept.');
  await page.locator('#operation-state').selectOption('failed');
  await expect(page.locator('#operation-action')).toHaveText('Try again');
  await page.locator('#operation-state').selectOption('succeeded');
  await expect(page.locator('#operation-meter')).toHaveAttribute('data-state', 'complete');
  await expect(page.locator('#operation-meter')).toHaveAttribute('aria-valuenow', '100');
  await page.getByRole('button', { name: 'Copy SHA-512', exact: true }).click();
  await expect(page.locator('#copy-sha512')).toHaveText('Copied');
  expect(await page.evaluate(() => window.fixtureClipboard)).toBe(await page.locator('#sha512-value').textContent());
  expect((await page.evaluate(() => window.fixtureClipboard)).length).toBe(128);
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('denied'); }; });
  await page.getByRole('button', { name: 'Copy SHA-256', exact: true }).click();
  await expect(page.locator('#copy-status')).toContainText('Could not copy');
  await expect(page.locator('#copy-sha256')).toHaveText('Copy');
  await page.getByRole('button', { name: 'Use matching example' }).click();
  await expect(page.locator('#comparison')).toHaveAttribute('data-state', 'match');
  await page.getByRole('button', { name: 'Use mismatch example' }).click();
  await expect(page.locator('#comparison')).toHaveAttribute('data-state', 'mismatch');
  await page.locator('#expected').fill('not a checksum');
  await expect(page.locator('#expected')).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Compare', exact: true }).click();
  await expect(page.locator('#expected')).toHaveAttribute('aria-invalid', 'true');
  await page.locator('#expected').fill('a'.repeat(32));
  await page.getByRole('button', { name: 'Compare', exact: true }).click();
  await expect(page.locator('#comparison-message')).toContainText('MD5 was not calculated');
  await page.locator('#expected').fill('');
  await page.getByRole('button', { name: 'Compare', exact: true }).click();
  await expect(page.locator('#comparison-message')).toHaveText('Paste an expected checksum to compare.');
  const help = page.getByRole('button', { name: 'Help & About' });
  await help.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(help).toBeFocused();
  for (const width of [800, 520, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const digest = page.locator('#sha512-value');
    expect(await digest.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  }
  await page.setViewportSize({width:800,height:900});
  await page.locator('#drop-state').selectOption('selected');
  await page.getByRole('button', {name:'Use matching example'}).click();
  await page.screenshot({path:'test-results/fruity-workflow.png',fullPage:true});
  await help.click();
  await page.getByRole('dialog').screenshot({path:'test-results/fruity-help.png'});
  expect(errors).toEqual([]);
  console.log('Passed: file states/focus, operation phases, canonical clipboard payload, comparison validation, help dialog, 3 widths, full SHA-512 wrapping, runtime errors.');
} finally { await browser.close(); }
